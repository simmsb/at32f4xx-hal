/// Built-in high speed clock frequency
pub const HICK: u32 = 48_000_000; // Hz

/// Minimum system clock frequency
pub const SYSCLK_MIN: u32 = 4_000_000;

/// Maximum system clock frequency
pub const SYSCLK_MAX: u32 = 150_000_000;

/// Maximum APB2 peripheral clock frequency
pub const PCLK2_MAX: u32 = SYSCLK_MAX / 2;

/// Maximum APB1 peripheral clock frequency
pub const PCLK1_MAX: u32 = SYSCLK_MAX / 2;

pub const HSI: u32 = 8_000_000;

#[derive(defmt::Format)]
pub struct CFGR {
    hext: Option<u32>,
    hext_bypass: bool,
    hclk: Option<u32>,
    pclk1: Option<u32>,
    pclk2: Option<u32>,
    sclk: Option<u32>,
    pll48clk: bool,
}

#[derive(defmt::Format)]
#[repr(u8)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum HPre {
    /// SYSCLK not divided
    Div1 = 7,
    /// SYSCLK divided by 2
    Div2 = 8,
    /// SYSCLK divided by 4
    Div4 = 9,
    /// SYSCLK divided by 8
    Div8 = 10,
    /// SYSCLK divided by 16
    Div16 = 11,
    /// SYSCLK divided by 64
    Div64 = 12,
    /// SYSCLK divided by 128
    Div128 = 13,
    /// SYSCLK divided by 256
    Div256 = 14,
    /// SYSCLK divided by 512
    Div512 = 15,
}

#[derive(defmt::Format)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum PPre {
    /// HCLK not divided
    Div1 = 0b11,
    /// HCLK divided by 2
    Div2 = 0b100,
    /// HCLK divided by 4
    Div4 = 0b101,
    /// HCLK divided by 8
    Div8 = 0b110,
    /// HCLK divided by 16
    Div16 = 0b111,
}

impl CFGR {
    /// Uses HEXT (external oscillator) instead of HICK (internal RC oscillator) as the clock source.
    /// Will result in a hang if an external oscillator is not connected or it fails to start.
    pub fn use_hext(mut self, freq: Hertz) -> Self {
        self.hext = Some(freq.raw());
        self
    }

    pub fn hclk(mut self, freq: Hertz) -> Self {
        self.hclk = Some(freq.raw());
        self
    }

    pub fn pclk1(mut self, freq: Hertz) -> Self {
        self.pclk1 = Some(freq.raw());
        self
    }

    pub fn pclk2(mut self, freq: Hertz) -> Self {
        self.pclk2 = Some(freq.raw());
        self
    }

    pub fn sclk(mut self, freq: Hertz) -> Self {
        self.sclk = Some(freq.raw());
        self
    }

    pub fn require_pll48clk(mut self) -> Self {
        self.pll48clk = true;
        self
    }

    fn flash_setup(sclk: u32) {
        use crate::pac::FLASH;

        let flash_latency_step = 32_000_000;

        unsafe {
            let flash = &(*FLASH::ptr());
            flash.psr().modify(|_, w| {
                w.pft_en().set_bit();
                w.wtcyc().bits(((sclk - 1) / flash_latency_step) as u8)
            });
        }
    }

    /// Initialises the hardware according to CFGR state returning a Clocks instance.
    /// Panics if overclocking is attempted.
    pub fn freeze(self) -> Clocks {
        self.freeze_internal(false)
    }

    /// Initialises the hardware according to CFGR state returning a Clocks instance.
    /// Allows overclocking.
    ///
    /// # Safety
    ///
    /// This method does not check if the clocks are bigger or smaller than the officially
    /// recommended.
    pub unsafe fn freeze_unchecked(self) -> Clocks {
        self.freeze_internal(true)
    }

    #[inline(always)]
    fn pll_setup(&self, pllsrcclk: u32, pllsysclk: Option<u32>) -> PllSetup {
        let main_pll = MainPll::fast_setup(
            pllsrcclk,
            self.hext.is_some(),
            Some(false),
            pllsysclk,
            self.pll48clk,
        );
        PllSetup {
            use_pll: main_pll.use_pll,
            pllsysclk: main_pll.pllsclk,
            pll48clk: main_pll.pll48clk,
        }
    }

    fn freeze_internal(self, unchecked: bool) -> Clocks {
        let crm = unsafe { &*CRM::ptr() };

        defmt::trace!("Starting clock freeze with: {}", self);

        let hse = self.hext;
        let hse_bypass = self.hext_bypass;
        let pllsrcclk = if let Some(hse) = hse { hse } else { HSI / 2 };

        let pllmul = if let Some(sysclk) = self.sclk {
            sysclk / pllsrcclk
        } else {
            1
        };

        let (pllmul_bits, sysclk) = if pllmul == 1 {
            (None, if let Some(hse) = hse { hse } else { HSI })
        } else {
            let pllmul = match pllmul {
                2..=64 => pllmul,
                0..=1 => 2,
                _ => 64,
            };

            (Some(pllmul as u8 - 2), pllsrcclk * pllmul)
        };

        let hpre_bits = if let Some(hclk) = self.hclk {
            match sysclk / hclk {
                0..=1 => HPre::Div1,
                2 => HPre::Div2,
                3..=5 => HPre::Div4,
                6..=11 => HPre::Div8,
                12..=39 => HPre::Div16,
                40..=95 => HPre::Div64,
                96..=191 => HPre::Div128,
                192..=383 => HPre::Div256,
                _ => HPre::Div512,
            }
        } else {
            HPre::Div1
        };

        let hclk = if hpre_bits as u8 >= 0b1100 {
            sysclk / (1 << (hpre_bits as u8 - 0b0110))
        } else {
            sysclk / (1 << (hpre_bits as u8 - 0b0111))
        };

        let pclk1 = if let Some(pclk1) = self.pclk1 {
            pclk1
        } else if hclk < 36_000_000 {
            hclk
        } else {
            36_000_000
        };
        let ppre1_bits = match (hclk + pclk1 - 1) / pclk1 {
            0..=1 => PPre::Div1,
            2 => PPre::Div2,
            3..=5 => PPre::Div4,
            6..=11 => PPre::Div8,
            _ => PPre::Div16,
        };

        let ppre2_bits = if let Some(pclk2) = self.pclk2 {
            match hclk.div_ceil(pclk2) {
                0..=1 => PPre::Div1,
                2 => PPre::Div2,
                3..=5 => PPre::Div4,
                6..=11 => PPre::Div8,
                _ => PPre::Div16,
            }
        } else {
            PPre::Div1
        };

        // let ppre2 = 1 << (ppre2_bits as u8 - 0b011);
        // let pclk2 = hclk / (ppre2 as u32);

        let sysclk = if let Some(pllmul_bits) = pllmul_bits {
            let pllsrcclk = if let Some(hse) = hse { hse } else { HSI / 2 };
            pllsrcclk * (pllmul_bits as u32 + 2)
        } else if let Some(hse) = hse {
            hse
        } else {
            HSI
        };

        let hclk = if hpre_bits as u8 >= 0b1100 {
            sysclk / (1 << (hpre_bits as u8 - 0b0110))
        } else {
            sysclk / (1 << (hpre_bits as u8 - 0b0111))
        };

        let ppre1 = 1 << (ppre1_bits as u8 - 0b011);
        let pclk1 = hclk / (ppre1 as u32);

        let ppre2 = 1 << (ppre2_bits as u8 - 0b011);
        let pclk2 = hclk / (ppre2 as u32);

        Self::flash_setup(sysclk);

        if hse.is_some() {
            crm.ctrl().modify(|_, w| {
                if hse_bypass {
                    w.hextbyps().enable();
                }
                w.hexten().enable();
                w
            });

            while crm.ctrl().read().hextstbl().bit_is_clear() {}
        }

        if let Some(pllmul_bits) = pllmul_bits {
            crm.cfg().modify(|_, w| unsafe {
                w.pllmult3_0().bits(pllmul_bits & 0b1111);
                w.pllmult5_4().bits((pllmul_bits >> 4) & 0b11);
                w.pllrcs().bit(hse.is_some());
                w
            });

            crm.ctrl().modify(|_, w| w.pllen().enable());

            while crm.ctrl().read().pllstbl().bit_is_clear() {}
        }

        defmt::trace!("ahb1div: {:b}, ahb2div: {:b}, ahbdiv: {:b}, pllmul: {:b}", ppre1_bits, ppre2_bits, hpre_bits, pllmul_bits);

        crm.cfg().modify(|_, w| unsafe {
            // adcpre?
            w.apb1div().bits(ppre1_bits as u8);
            w.apb2div().bits(ppre2_bits as u8);
            w.ahbdiv().bits(hpre_bits as u8);
            w.sclksel().bits(if pllmul_bits.is_some() {
                0b10
            } else if hse.is_some() {
                0b1
            } else {
                0b0
            });
            w
        });

        let tmr1clk = Hertz::from_raw(pclk1 * if ppre1 == 1 { 1 } else { 2 });
        let tmr2clk = Hertz::from_raw(pclk2 * if ppre2 == 1 { 1 } else { 2 });

        Clocks {
            sclk: sysclk.Hz(),
            hclk: hclk.Hz(),
            pclk1: pclk1.Hz(),
            pclk2: pclk2.Hz(),
            tmr1clk,
            tmr2clk,
            usb48m: None,
        }
    }
}

