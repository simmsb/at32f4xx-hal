/// Bus associated to peripheral
pub trait CrmBus: crate::Sealed {
    /// Bus type;
    type Bus;
}

/// Enable/disable peripheral
#[allow(clippy::missing_safety_doc)]
pub trait Enable: CrmBus {
    /// Enables peripheral
    fn enable(crm: &CrmRB);

    /// Disables peripheral
    fn disable(crm: &CrmRB);

    /// Check if peripheral enabled
    fn is_enabled() -> bool;

    /// Check if peripheral disabled
    #[inline]
    fn is_disabled() -> bool {
        !Self::is_enabled()
    }

    /// # Safety
    ///
    /// Enables peripheral. Takes access to CRM internally
    unsafe fn enable_unchecked() {
        let crm = unsafe { pac::CRM::ptr().as_ref().unwrap() };
        Self::enable(crm);
    }

    /// # Safety
    ///
    /// Disables peripheral. Takes access to CRM internally
    unsafe fn disable_unchecked() {
        let crm = unsafe { pac::CRM::ptr().as_ref().unwrap() };
        Self::disable(crm);
    }
}

/// Reset peripheral
#[allow(clippy::missing_safety_doc)]
pub trait Reset: CrmBus {
    /// Resets peripheral
    fn reset(crm: &CrmRB);

    /// # Safety
    ///
    /// Resets peripheral. Takes access to CRM internally
    unsafe fn reset_unchecked() {
        let crm = unsafe { pac::CRM::ptr().as_ref().unwrap() };
        Self::reset(crm);
    }
}

/// Extension trait that constrains the `CRM` peripheral
pub trait CrmExt {
    /// Constrains the `CRM` peripheral so it plays nicely with the other abstractions
    fn constrain(self) -> Crm;
}

/// Frequency on bus that peripheral is connected in
pub trait BusClock {
    /// Calculates frequency depending on `Clock` state
    fn clock(clocks: &Clocks) -> Hertz;
}

/// Frequency on bus that timer is connected in
pub trait BusTimerClock {
    /// Calculates base frequency of timer depending on `Clock` state
    fn timer_clock(clocks: &Clocks) -> Hertz;
}

impl<T> BusClock for T
where
    T: CrmBus,
    T::Bus: BusClock,
{
    fn clock(clocks: &Clocks) -> Hertz {
        T::Bus::clock(clocks)
    }
}

impl<T> BusTimerClock for T
where
    T: CrmBus,
    T::Bus: BusTimerClock,
{
    fn timer_clock(clocks: &Clocks) -> Hertz {
        T::Bus::timer_clock(clocks)
    }
}

